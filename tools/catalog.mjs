#!/usr/bin/env node
// DWCode extension catalog: turns the licence gate's output into the data file
// and the card grid that https://dwcode.pages.dev/repository serves.
//
//   node tools/catalog.mjs build    # network: re-run the gate, join the curated
//                                   # content, write site/data/catalog.json
//   node tools/catalog.mjs render   # offline: write the card grid into
//                                   # site/repository.html between the markers
//   node tools/catalog.mjs index    # offline: write the machine-readable install
//                                   # index site/data/catalog/index.json + .sha256
//   node tools/catalog.mjs check    # offline: validate data, HTML and index (CI gate)
//
// Four files, four jobs:
//   tools/catalog-content.json  hand-written: family + one original line per id,
//                               plus the `omit` list (licence-clean but not
//                               offered) with the reason for each.
//   site/data/catalog.json      generated by `build`, committed, and the single
//                               source both the HTML and the check read.
//   site/data/catalog/index.json  generated by `index`, committed: the install
//                               contract (docs/PACK_INDEX.md) the app fetches.
//   site/repository.html        holds the rendered grid between
//                               <!-- CATALOG:BEGIN --> / <!-- CATALOG:END -->,
//                               so the page works before any JavaScript runs.
//
// Nothing here copies upstream presentation: cards carry the name, publisher,
// version, licence, download count and a link to the publisher's own repository
// (falling back to the Open VSX listing when no repository is published). No
// icons, artwork, screenshots, ratings or listing text are taken from anywhere.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { collectPacks } from './build-pack.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SCAN = join(HERE, 'openvsx-scan.mjs');
const CONTENT = join(HERE, 'catalog-content.json');
const VERIFIED = join(HERE, 'openvsx-verified.json');
const DOC = join(ROOT, 'FOSS_EXTENSION_REPOSITORY.md');
const DATA = join(ROOT, 'site', 'data', 'catalog.json');
const PAGE = join(ROOT, 'site', 'repository.html');
const INDEX = join(ROOT, 'site', 'data', 'catalog', 'index.json');
const BEGIN = '<!-- CATALOG:BEGIN -->';
const END = '<!-- CATALOG:END -->';

// The install contract. Kept as constants because a client that reads a
// different schema than the one it was built against must refuse the file
// rather than guess — see docs/PACK_INDEX.md.
const INDEX_KIND = 'dwcode-pack-index';
const INDEX_SCHEMA = 1;
const SITE_BASE = 'https://dwcode.pages.dev';
const MAX_INDEX_BYTES = 8 * 1024 * 1024;
const MAX_ARTIFACT_BYTES = 64 * 1024 * 1024;
const HEX64 = /^[0-9a-f]{64}$/;
// Semver, pre-release and all: registries really do publish `1.0.0-rc.1`, and
// refusing those would drop live rows from the index instead of describing
// them. Build metadata (`+build`) is allowed too — a version is provenance,
// not a filename.
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

// `SEE LICENSE IN LICENSE.md → MIT (verified 2026-10-26)` → `MIT`
const shortLicense = (license) => {
  const i = String(license).indexOf(' → ');
  return i >= 0 ? license.slice(i + 3).replace(/ \(verified .*\)$/, '') : license;
};
const downloads = (n) => (n >= 1e6
  ? `${+(n / 1e6).toFixed(2)} M`
  : n >= 1e3 ? `${Math.round(n / 1e3)} K` : String(n));

// Deterministic two-letter monogram + one of four token-coloured tiles, both
// derived from the id — never a publisher's artwork.
const initials = (name) => {
  const words = String(name).replace(/[^A-Za-z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
  const a = words[0] || '?';
  const b = words.length > 1 ? words[1] : '';
  return (a[0] + (b[0] || a[1] || '')).toUpperCase();
};
const tileClass = (id) => {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return `g${h % 4}`;
};

const registryUrl = (id) => {
  const i = id.lastIndexOf('.');
  return `https://open-vsx.org/extension/${id.slice(0, i)}/${id.slice(i + 1)}`;
};

// ---------------------------------------------------------------- build
function build() {
  const content = JSON.parse(readFileSync(CONTENT, 'utf8'));
  const scan = spawnSync(process.execPath, [SCAN, '--doc', '--json'], {
    cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024,
  });
  if (scan.status !== 0 && scan.status !== 1) {
    console.error(`catalog: gate failed to run (exit ${scan.status})\n${scan.stderr}`);
    process.exit(1);
  }
  let report;
  try {
    report = JSON.parse(scan.stdout);
  } catch {
    console.error(`catalog: gate did not emit JSON\n${scan.stderr}`);
    process.exit(1);
  }

  const eligible = report.rows.filter((r) => r.verdict === 'accept' || r.verdict === 'verified');
  const cards = [];
  const problems = [];

  for (const r of eligible) {
    if (r.id in content.omit) continue;           // offered-elsewhere, see omit reasons
    const entry = content.entries[r.id];
    if (!entry) { problems.push(`no content for ${r.id} — add family + blurb to catalog-content.json`); continue; }
    if (!(entry.family in content.families)) { problems.push(`${r.id}: unknown family "${entry.family}"`); continue; }
    // Credit rule: every card links the publisher's own repository. Two packages
    // publish none (kide.*), and inventing a link would be worse than admitting
    // it — their licence chip falls back to the Open VSX listing and says so.
    const repository = r.repository?.startsWith('http') ? r.repository : null;
    if (!repository) console.error(`catalog: note — ${r.id} publishes no repository; crediting the Open VSX listing instead`);
    cards.push({
      id: r.id,
      name: (r.name || r.id).trim(),
      publisher: r.id.slice(0, r.id.lastIndexOf('.')),
      family: entry.family,
      blurb: entry.blurb,
      license: shortLicense(r.license),
      licenseFull: r.license,
      verified: r.verdict === 'verified',
      version: r.version || '',
      downloads: r.downloads,
      downloadsLabel: downloads(r.downloads),
      repository,
      registry: registryUrl(r.id),
    });
  }

  for (const id of Object.keys(content.omit)) {
    if (!eligible.some((r) => r.id === id)) console.error(`catalog: note — omit "${id}" is not currently catalog-eligible (nothing to hide)`);
  }
  if (problems.length) {
    console.error(`catalog: refusing to build —\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }

  cards.sort((a, b) => b.downloads - a.downloads || a.id.localeCompare(b.id));
  const families = Object.entries(content.families).map(([key, label]) => ({
    key,
    label,
    count: cards.filter((c) => c.family === key).length,
  })).filter((f) => f.count > 0);

  const out = {
    generated: new Date().toISOString().slice(0, 10),
    source: 'Open VSX registry API (open-vsx.org) + upstream licence files',
    note: 'Generated by `node tools/catalog.mjs build`. Names, counts and links are facts about each package; all packages remain the property of their publishers under the licences shown.',
    gate: {
      checked: report.checked,
      eligible: report.eligible,
      pending: report.pending,
      refused: report.excluded,
      absent: report.missing,
    },
    omitted: Object.keys(content.omit).length,
    families,
    cards,
  };
  writeFileSync(DATA, `${JSON.stringify(out, null, 2)}\n`);
  console.error(`catalog: ${cards.length} cards · ${families.length} families · ${report.checked} gate ids (${report.pending} pending) → site/data/catalog.json`);
  // The index is derived from the data file, so regenerate it in the same
  // breath — otherwise a fresh build and a stale index would disagree until
  // somebody remembered a second command.
  buildIndex();
}

// ---------------------------------------------------------------- index
// The machine-readable twin of the card grid: everything the site shows a
// human, plus the artifact coordinates a client needs to actually install a
// first-party pack. Third-party rows stay `kind: "reference"` with
// `download: null` — DWCode does not redistribute them, and an install there
// is an act at the publisher's registry (docs/PACK_INDEX.md §1).

const KNOWN_ENTRY_KEYS = new Set([
  'id', 'name', 'publisher', 'version', 'family', 'kind', 'tier', 'license',
  'licenseFull', 'verified', 'capabilities', 'upstream', 'registry', 'source',
  'download',
]);
const KNOWN_DOWNLOAD_KEYS = new Set(['url', 'sha256', 'size']);
const LOOPBACK = new Set(['127.0.0.1', 'localhost', '::1', '[::1]']);

function buildIndex() {
  if (!existsSync(DATA)) {
    console.error('catalog: site/data/catalog.json missing — run `node tools/catalog.mjs build` first');
    process.exit(1);
  }
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const packs = collectPacks();

  const entries = packs.map((p) => ({
    id: p.id,
    name: p.displayName,
    publisher: 'cybercoretech',
    version: p.version,
    family: 'first-party',
    kind: 'pack',
    tier: 'declarative',
    license: p.license,
    licenseFull: p.license,
    verified: true,
    capabilities: p.capabilities,
    upstream: 'https://github.com/cybercoretech/dwcode',
    registry: null,
    source: 'first-party',
    download: { url: p.url, sha256: p.sha256, size: p.size },
  }));

  for (const c of data.cards) {
    entries.push({
      id: c.id,
      name: c.name,
      publisher: c.publisher,
      version: c.version,
      family: c.family,
      kind: 'reference',
      tier: 'reference',
      license: c.license,
      licenseFull: c.licenseFull,
      verified: c.verified,
      capabilities: [],
      upstream: c.repository,
      registry: c.registry,
      source: 'openvsx',
      download: null,
    });
  }

  const index = {
    kind: INDEX_KIND,
    schema: INDEX_SCHEMA,
    generated: data.generated,
    app: { min: '0.1.0' },
    base: SITE_BASE,
    gate: data.gate,
    entries,
  };

  const body = `${JSON.stringify(index, null, 2)}\n`;
  if (Buffer.byteLength(body) > MAX_INDEX_BYTES) {
    console.error(`catalog: refusing to write a ${Buffer.byteLength(body)}-byte index (limit ${MAX_INDEX_BYTES})`);
    process.exit(1);
  }
  mkdirSync(dirname(INDEX), { recursive: true });
  const digest = createHash('sha256').update(body).digest('hex');
  writeFileSync(INDEX, body);
  writeFileSync(`${INDEX}.sha256`, `${digest}  index.json\n`);
  console.error(`catalog: ${entries.length} index entries (${packs.length} installable, ${data.cards.length} reference) → site/data/catalog/index.json sha256 ${digest}`);
}

// Shared by `check`: the same rules `PackIndex::parse()` enforces in C++, so a
// file that passes here cannot be refused by the app for the same reason, and
// a file that fails here never reaches a deploy.
function validateIndex(problems) {
  const fail = (m) => problems.push(`index: ${m}`);
  if (!existsSync(INDEX)) {
    fail('site/data/catalog/index.json missing — run `node tools/catalog.mjs index`');
    return;
  }
  const body = readFileSync(INDEX);
  if (body.length > MAX_INDEX_BYTES) { fail(`file is ${body.length} bytes, over the ${MAX_INDEX_BYTES} limit`); return; }

  let index;
  try { index = JSON.parse(body.toString('utf8')); } catch (e) { fail(`not valid JSON: ${e.message}`); return; }

  if (index.kind !== INDEX_KIND) fail(`kind is ${JSON.stringify(index.kind)}, expected "${INDEX_KIND}"`);
  if (index.schema !== INDEX_SCHEMA) fail(`schema is ${JSON.stringify(index.schema)}, expected ${INDEX_SCHEMA} — a client must refuse a format it does not know`);
  if (!SEMVER.test(index.app?.min || '')) fail(`app.min must be X.Y.Z, got ${JSON.stringify(index.app?.min)}`);
  if (index.base !== SITE_BASE) fail(`base is ${JSON.stringify(index.base)}, expected ${SITE_BASE}`);
  if (!Array.isArray(index.entries) || !index.entries.length) { fail('entries is empty'); return; }

  const expectedKeys = Object.keys(index).sort().join(',');
  if (expectedKeys !== 'app,base,entries,gate,generated,kind,schema') fail(`unexpected top-level keys: ${expectedKeys}`);

  const seen = new Set();
  const cardRows = JSON.parse(readFileSync(DATA, 'utf8')).cards;
  const cards = new Map(cardRows.map((c) => [c.id, c]));
  const content = JSON.parse(readFileSync(CONTENT, 'utf8'));
  const packs = collectPacks();
  const packIds = new Set(packs.map((p) => p.id));

  for (const entry of index.entries) {
    const at = (m) => fail(`${entry?.id || '<no id>'}: ${m}`);
    if (!entry || typeof entry !== 'object') { fail('entry is not an object'); continue; }
    for (const key of Object.keys(entry)) if (!KNOWN_ENTRY_KEYS.has(key)) at(`unknown key "${key}" — the schema is fixed, not open-ended`);
    if (!entry.id || seen.has(entry.id)) at(!entry.id ? 'missing id' : 'duplicate id');
    seen.add(entry.id);
    if (!entry.name) at('missing name');
    if (!entry.publisher) at('missing publisher');
    if (!SEMVER.test(entry.version || '')) at(`version must be semver (X.Y.Z with optional -pre/+build), got ${JSON.stringify(entry.version)}`);
    if (!entry.family) at('missing family');
    if (!['pack', 'reference'].includes(entry.kind)) at(`kind must be "pack" or "reference", got ${JSON.stringify(entry.kind)}`);
    if (!entry.tier) at('missing tier (compatibility report)');
    if (!entry.license) at('missing licence');
    if (!entry.licenseFull) at('missing licenseFull');
    if (!Array.isArray(entry.capabilities) || entry.capabilities.some((c) => typeof c !== 'string')) at('capabilities must be an array of strings');
    if (entry.upstream !== null && !/^https?:\/\//.test(entry.upstream || '')) at('upstream is neither null nor a url');
    if (entry.registry !== null && !/^https:\/\/open-vsx\.org\/extension\/[^/]+\/[^/]+$/.test(entry.registry || '')) at(`registry must be an Open VSX extension url, got ${JSON.stringify(entry.registry)}`);
    if (!entry.upstream && !entry.registry) at('nothing to credit: both upstream and registry are null');
    if (entry.source !== 'first-party' && entry.source !== 'openvsx') at(`source must be "first-party" or "openvsx", got ${JSON.stringify(entry.source)}`);

    // kind ⟺ download, both directions, with no exceptions.
    if (entry.kind === 'pack') {
      if (!entry.download || typeof entry.download !== 'object') { at('kind "pack" requires a download object'); continue; }
      for (const key of Object.keys(entry.download)) if (!KNOWN_DOWNLOAD_KEYS.has(key)) at(`download: unknown key "${key}"`);
      const d = entry.download;
      let url;
      try { url = new URL(d.url); } catch { at(`download.url is not an absolute url: ${JSON.stringify(d.url)}`); continue; }
      if (url.protocol === 'http:') {
        if (!LOOPBACK.has(url.hostname)) at(`download.url is plain http to ${url.hostname} — only loopback may be unencrypted`);
      } else if (url.protocol !== 'https:') {
        at(`download.url scheme must be https, got ${url.protocol}`);
      }
      if (typeof d.sha256 !== 'string' || !HEX64.test(d.sha256)) at(`download.sha256 must be 64 lowercase hex, got ${JSON.stringify(d.sha256)}`);
      if (!Number.isInteger(d.size) || d.size < 1 || d.size > MAX_ARTIFACT_BYTES) at(`download.size must be an integer in 1..${MAX_ARTIFACT_BYTES}, got ${JSON.stringify(d.size)}`);
      if (!packIds.has(entry.id)) at('kind "pack" but the pack is not built by tools/build-pack.mjs');
      const pack = packs.find((p) => p.id === entry.id);
      if (pack) {
        if (pack.version !== entry.version) at(`version ${entry.version} != manifest ${pack.version}`);
        if (d.sha256 !== pack.sha256) at(`sha256 ${d.sha256} != rebuilt artifact ${pack.sha256} — the pack source changed; re-run \`node tools/catalog.mjs index\``);
        if (d.size !== pack.size) at(`size ${d.size} != rebuilt artifact ${pack.size}`);
        if (d.url !== pack.url) at(`url ${d.url} != expected ${pack.url}`);
      }
    } else if (entry.download !== null) {
      at('kind "reference" must have download: null — DWCode does not redistribute third-party packages');
    }

    if (entry.kind === 'reference') {
      const card = cards.get(entry.id);
      if (!card) at('reference row is not in site/data/catalog.json');
      else {
        // Drift check: the page and the index are two renderings of one fact
        // base. A version, licence or family that differs between them means
        // one of them was edited by hand.
        if (card.version !== entry.version) at(`version ${entry.version} != catalog.json ${card.version}`);
        if (card.license !== entry.license) at(`licence ${entry.license} != catalog.json ${card.license}`);
        if (card.family !== entry.family) at(`family ${entry.family} != catalog.json ${card.family}`);
        if (card.licenseFull !== entry.licenseFull) at('licenseFull differs from catalog.json');
        if ((card.repository ?? null) !== (entry.upstream ?? null)) at('upstream differs from catalog.json repository');
        if (card.registry !== entry.registry) at('registry differs from catalog.json');
        if (card.verified !== entry.verified) at('verified differs from catalog.json');
      }
    }
    if (entry.id in content.omit) at('id is on the omit list and must never reach the index');
  }

  for (const card of cardRows) if (!seen.has(card.id)) fail(`card ${card.id} is missing from the index`);
  for (const pack of packs) if (!seen.has(pack.id)) fail(`first-party pack ${pack.id} is missing from the index`);

  const shaFile = `${INDEX}.sha256`;
  if (!existsSync(shaFile)) {
    fail('index.json.sha256 missing — a client cannot record which index authorized an install');
  } else {
    const line = readFileSync(shaFile, 'utf8').trim();
    const digest = createHash('sha256').update(body).digest('hex');
    if (line !== `${digest}  index.json`) fail(`index.json.sha256 says "${line}", but the file hashes to "${digest}  index.json" — re-run \`node tools/catalog.mjs index\``);
  }
}

// ---------------------------------------------------------------- render
function cardHtml(c) {
  const upstream = c.repository || c.registry;
  const licenceTitle = !c.repository
    ? `${c.licenseFull} — this publisher lists no source repository, so this link goes to its Open VSX entry instead`
    : c.verified
      ? `${c.licenseFull} — registry field was a pointer; upstream LICENSE read and recorded in tools/openvsx-verified.json`
      : c.licenseFull;
  return `        <article class="xcard" data-id="${esc(c.id)}" data-name="${esc(c.name.toLowerCase())}" data-pub="${esc(c.publisher.toLowerCase())}" data-family="${esc(c.family)}" data-lic="${esc(c.license.toLowerCase())}" data-dl="${c.downloads}">
          <div class="xc-top">
            <span class="xglyph ${tileClass(c.id)}" aria-hidden="true">${esc(initials(c.name))}</span>
            <div class="xc-id">
              <h3 class="xc-name">${esc(c.name)}</h3>
              <p class="xc-pub">${esc(c.publisher)} <span class="xc-sep">·</span> ${esc(c.version || '—')}</p>
            </div>
          </div>
          <p class="xc-blurb">${esc(c.blurb)}</p>
          <ul class="xc-chips">
            <li><a class="chip chip-lic" href="${esc(upstream)}" target="_blank" rel="noopener" title="${esc(licenceTitle)}">${esc(c.license)}<span class="sr"> — licence, opens the publisher's repository in a new tab</span></a></li>
            <li><span class="chip chip-dl" title="Open VSX downloads">${esc(c.downloadsLabel)}</span></li>
            <li><span class="chip chip-fam">${esc(c.family)}</span></li>
          </ul>
          <div class="xc-actions">
            <button class="btn btn-ghost btn-sm" type="button" data-copy-id="${esc(c.id)}">copy id</button>
            <a class="btn btn-ghost btn-sm" href="${esc(c.registry)}" target="_blank" rel="noopener">registry <span aria-hidden="true">↗</span><span class="sr"> (opens in a new tab)</span></a>
            <span class="btn btn-sm xc-install" role="img" aria-label="Install is not available yet: the catalog index ships with milestone M5" title="Ships with M5 — the checksum-pinned catalog index is not live yet">install · M5</span>
          </div>
        </article>`;
}

function render() {
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const page = readFileSync(PAGE, 'utf8');
  const start = page.indexOf(BEGIN);
  const stop = page.indexOf(END);
  if (start < 0 || stop < 0 || stop < start) {
    console.error(`catalog: ${PAGE} is missing the ${BEGIN} / ${END} markers`);
    process.exit(1);
  }

  const all = data.families.length;
  const stats = `        <p class="cat-stats"><span class="mono">${data.cards.length} extensions</span><span class="mono">${all} families</span><span class="mono">licence gate: ${data.gate.pending} pending</span><span class="mono">generated ${esc(data.generated)}</span></p>\n`;
  const cats = [
    `            <li><button class="cat is-on" type="button" data-family="all" aria-pressed="true">All extensions <span class="cat-n">${data.cards.length}</span></button></li>`,
    ...data.families.map((f) => `            <li><button class="cat" type="button" data-family="${esc(f.key)}" aria-pressed="false">${esc(f.label)} <span class="cat-n">${f.count}</span></button></li>`),
  ].join('\n');
  const grid = data.cards.map(cardHtml).join('\n');

  const block = `${BEGIN}
        <div class="cat-stats">
          <span class="mono">${data.cards.length} extensions</span>
          <span class="mono">${all} families</span>
          <span class="mono">licence gate: ${data.gate.pending} pending</span>
          <span class="mono">generated ${esc(data.generated)}</span>
        </div>
        <div class="catalog">
          <aside class="rail" aria-labelledby="cats-h">
            <p class="rail-h" id="cats-h">// categories</p>
            <ul class="cats" role="list">
${cats}
            </ul>
            <p class="rail-foot">Families group extensions by what they <em>are</em>, not by the language they touch. Every row passed the licence gate in <span class="mono">npm run catalog:scan</span>.</p>
          </aside>
          <div class="catalog-main">
            <div class="toolbar">
              <label class="sr" for="cat-q">Search extensions</label>
              <input class="cat-q" id="cat-q" type="search" placeholder="/ search extensions, publishers, ids…" autocomplete="off" spellcheck="false">
              <label class="sr" for="cat-sort">Sort by</label>
              <select class="cat-sort" id="cat-sort">
                <option value="dl">downloads · high to low</option>
                <option value="name">name · a to z</option>
                <option value="lic">licence</option>
                <option value="pub">publisher</option>
              </select>
              <output class="cat-count" id="cat-count" aria-live="polite" for="cat-q">${data.cards.length} shown</output>
            </div>
            <div class="xgrid" id="xgrid">
${grid}
            </div>
            <p class="cat-empty" id="cat-empty" hidden><b>// no match</b> Nothing in the catalog matches that search and category. Clear the search, or pick another family.</p>
          </div>
        </div>
      ${END}`;
  writeFileSync(PAGE, `${page.slice(0, start)}${block}${page.slice(stop + END.length)}`);
  console.error(`catalog: rendered ${data.cards.length} cards into site/repository.html`);
}

// ---------------------------------------------------------------- check
function check() {
  const fail = (msg) => { console.error(`catalog: ${msg}`); process.exit(1); };
  if (!existsSync(DATA)) fail('site/data/catalog.json missing — run `node tools/catalog.mjs build`');
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const content = JSON.parse(readFileSync(CONTENT, 'utf8'));
  const verified = JSON.parse(readFileSync(VERIFIED, 'utf8'));
  const problems = [];
  const ids = new Set();

  if (!Array.isArray(data.cards) || data.cards.length === 0) fail('catalog has no cards');

  for (const c of data.cards) {
    const at = (m) => problems.push(`${c.id}: ${m}`);
    if (ids.has(c.id)) at('duplicate id');
    ids.add(c.id);
    if (c.id in content.omit) at('listed but omitted from the site');
    if (!(c.family in content.families)) at('unknown family');
    if (!c.name || !c.blurb) at('missing name or blurb');
    if (c.blurb && c.blurb.length > 160) at('blurb too long for a card');
    if (!c.license) at('missing licence');
    if (!Number.isFinite(c.downloads)) at('downloads is not a number');
    if (!/^https:\/\/open-vsx\.org\/extension\/[^/]+\/[^/]+$/.test(c.registry)) at('bad registry url');
    if (c.repository !== null && !/^https?:\/\//.test(c.repository)) at('repository is neither null nor a url');
    if (!c.repository && !c.registry.startsWith('https://open-vsx.org/extension/')) at('no repository and no registry link to credit');
    if (c.id in verified && verified[c.id].spdx === 'NONE') at('id is a recorded refusal');
  }
  for (const [id, why] of Object.entries(content.omit)) {
    if (ids.has(id)) problems.push(`${id}: on the omit list but present (${why.slice(0, 40)}…)`);
  }

  // Every card must appear in the document appendix, which only the gate's
  // accept/verified rows reach — this is what keeps the site and the licence
  // gate from drifting apart while both are offline.
  const doc = readFileSync(DOC, 'utf8');
  for (const c of data.cards) if (!doc.includes(`\`${c.id}\``)) problems.push('id not present in FOSS_EXTENSION_REPOSITORY.md');

  const page = readFileSync(PAGE, 'utf8');
  const start = page.indexOf(BEGIN);
  const stop = page.indexOf(END);
  if (start < 0 || stop < 0 || stop < start) {
    problems.push('repository.html is missing the CATALOG markers');
  } else {
    const block = page.slice(start, stop);
    const shown = [...block.matchAll(/data-id="([^"]+)"/g)].map((m) => m[1]);
    if (shown.length !== data.cards.length) problems.push(`HTML shows ${shown.length} cards, catalog.json has ${data.cards.length} — run \`node tools/catalog.mjs render\``);
    for (const id of shown) if (!ids.has(id)) problems.push(`HTML card ${id} is not in catalog.json`);
    const familiesShown = [...block.matchAll(/<article class="xcard"[^>]*data-family="([^"]+)"/g)].length;
    if (familiesShown !== shown.length) problems.push('a card is missing its data-family attribute');
  }

  // The install index is the same data in the shape the app reads, so it is
  // held to the same standard: the page and the client must never disagree
  // about what exists, what it costs, or where it comes from.
  validateIndex(problems);

  if (problems.length) {
    console.error(`catalog: ${problems.length} problem(s) —\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.error(`catalog: OK — ${data.cards.length} cards, ${data.families.length} families, HTML and index in sync, no refused ids, every card credited`);
}

// ---------------------------------------------------------------- cli
const mode = process.argv[2];
if (mode === 'build') build();
else if (mode === 'render') render();
else if (mode === 'index') buildIndex();
else if (mode === 'check') check();
else {
  console.error('usage: node tools/catalog.mjs build|render|index|check');
  process.exit(2);
}

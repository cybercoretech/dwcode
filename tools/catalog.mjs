#!/usr/bin/env node
// DWCode extension catalog: turns the licence gate's output into the data file
// and the card grid that https://dwcode.pages.dev/repository serves.
//
//   node tools/catalog.mjs build    # network: re-run the gate, join the curated
//                                   # content, write site/data/catalog.json
//   node tools/catalog.mjs render   # offline: write the card grid into
//                                   # site/repository.html between the markers
//   node tools/catalog.mjs check    # offline: validate data + HTML (CI gate)
//
// Three files, three jobs:
//   tools/catalog-content.json  hand-written: family + one original line per id,
//                               plus the `omit` list (licence-clean but not
//                               offered) with the reason for each.
//   site/data/catalog.json      generated by `build`, committed, and the single
//                               source both the HTML and the check read.
//   site/repository.html        holds the rendered grid between
//                               <!-- CATALOG:BEGIN --> / <!-- CATALOG:END -->,
//                               so the page works before any JavaScript runs.
//
// Nothing here copies upstream presentation: cards carry the name, publisher,
// version, licence, download count and a link to the publisher's own repository
// (falling back to the Open VSX listing when no repository is published). No
// icons, artwork, screenshots, ratings or listing text are taken from anywhere.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SCAN = join(HERE, 'openvsx-scan.mjs');
const CONTENT = join(HERE, 'catalog-content.json');
const VERIFIED = join(HERE, 'openvsx-verified.json');
const DOC = join(ROOT, 'FOSS_EXTENSION_REPOSITORY.md');
const DATA = join(ROOT, 'site', 'data', 'catalog.json');
const PAGE = join(ROOT, 'site', 'repository.html');
const BEGIN = '<!-- CATALOG:BEGIN -->';
const END = '<!-- CATALOG:END -->';

const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

// `SEE LICENSE IN LICENSE.md → MIT (verified 2026-10-26)` → `MIT`
const shortLicense = (license) => {
  const i = String(license).indexOf(' → ');
  return i >= 0 ? license.slice(i + 3).replace(/ \(verified .*\)$/, '') : license;
};
const downloads = (n) => (n >= 1e6
  ? `${+(n / 1e6).toFixed(2)} M`
  : n >= 1e3 ? `${Math.round(n / 1e3)} K` : String(n));

// Deterministic two-letter monogram + one of four token-coloured tiles, both
// derived from the id — never a publisher's artwork.
const initials = (name) => {
  const words = String(name).replace(/[^A-Za-z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
  const a = words[0] || '?';
  const b = words.length > 1 ? words[1] : '';
  return (a[0] + (b[0] || a[1] || '')).toUpperCase();
};
const tileClass = (id) => {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return `g${h % 4}`;
};

const registryUrl = (id) => {
  const i = id.lastIndexOf('.');
  return `https://open-vsx.org/extension/${id.slice(0, i)}/${id.slice(i + 1)}`;
};

// ---------------------------------------------------------------- build
function build() {
  const content = JSON.parse(readFileSync(CONTENT, 'utf8'));
  const scan = spawnSync(process.execPath, [SCAN, '--doc', '--json'], {
    cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024,
  });
  if (scan.status !== 0 && scan.status !== 1) {
    console.error(`catalog: gate failed to run (exit ${scan.status})\n${scan.stderr}`);
    process.exit(1);
  }
  let report;
  try {
    report = JSON.parse(scan.stdout);
  } catch {
    console.error(`catalog: gate did not emit JSON\n${scan.stderr}`);
    process.exit(1);
  }

  const eligible = report.rows.filter((r) => r.verdict === 'accept' || r.verdict === 'verified');
  const cards = [];
  const problems = [];

  for (const r of eligible) {
    if (r.id in content.omit) continue;           // offered-elsewhere, see omit reasons
    const entry = content.entries[r.id];
    if (!entry) { problems.push(`no content for ${r.id} — add family + blurb to catalog-content.json`); continue; }
    if (!(entry.family in content.families)) { problems.push(`${r.id}: unknown family "${entry.family}"`); continue; }
    // Credit rule: every card links the publisher's own repository. Two packages
    // publish none (kide.*), and inventing a link would be worse than admitting
    // it — their licence chip falls back to the Open VSX listing and says so.
    const repository = r.repository?.startsWith('http') ? r.repository : null;
    if (!repository) console.error(`catalog: note — ${r.id} publishes no repository; crediting the Open VSX listing instead`);
    cards.push({
      id: r.id,
      name: (r.name || r.id).trim(),
      publisher: r.id.slice(0, r.id.lastIndexOf('.')),
      family: entry.family,
      blurb: entry.blurb,
      license: shortLicense(r.license),
      licenseFull: r.license,
      verified: r.verdict === 'verified',
      version: r.version || '',
      downloads: r.downloads,
      downloadsLabel: downloads(r.downloads),
      repository,
      registry: registryUrl(r.id),
    });
  }

  for (const id of Object.keys(content.omit)) {
    if (!eligible.some((r) => r.id === id)) console.error(`catalog: note — omit "${id}" is not currently catalog-eligible (nothing to hide)`);
  }
  if (problems.length) {
    console.error(`catalog: refusing to build —\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }

  cards.sort((a, b) => b.downloads - a.downloads || a.id.localeCompare(b.id));
  const families = Object.entries(content.families).map(([key, label]) => ({
    key,
    label,
    count: cards.filter((c) => c.family === key).length,
  })).filter((f) => f.count > 0);

  const out = {
    generated: new Date().toISOString().slice(0, 10),
    source: 'Open VSX registry API (open-vsx.org) + upstream licence files',
    note: 'Generated by `node tools/catalog.mjs build`. Names, counts and links are facts about each package; all packages remain the property of their publishers under the licences shown.',
    gate: {
      checked: report.checked,
      eligible: report.eligible,
      pending: report.pending,
      refused: report.excluded,
      absent: report.missing,
    },
    omitted: Object.keys(content.omit).length,
    families,
    cards,
  };
  writeFileSync(DATA, `${JSON.stringify(out, null, 2)}\n`);
  console.error(`catalog: ${cards.length} cards · ${families.length} families · ${report.checked} gate ids (${report.pending} pending) → site/data/catalog.json`);
}

// ---------------------------------------------------------------- render
function cardHtml(c) {
  const upstream = c.repository || c.registry;
  const licenceTitle = !c.repository
    ? `${c.licenseFull} — this publisher lists no source repository, so this link goes to its Open VSX entry instead`
    : c.verified
      ? `${c.licenseFull} — registry field was a pointer; upstream LICENSE read and recorded in tools/openvsx-verified.json`
      : c.licenseFull;
  return `        <article class="xcard" data-id="${esc(c.id)}" data-name="${esc(c.name.toLowerCase())}" data-pub="${esc(c.publisher.toLowerCase())}" data-family="${esc(c.family)}" data-lic="${esc(c.license.toLowerCase())}" data-dl="${c.downloads}">
          <div class="xc-top">
            <span class="xglyph ${tileClass(c.id)}" aria-hidden="true">${esc(initials(c.name))}</span>
            <div class="xc-id">
              <h3 class="xc-name">${esc(c.name)}</h3>
              <p class="xc-pub">${esc(c.publisher)} <span class="xc-sep">·</span> ${esc(c.version || '—')}</p>
            </div>
          </div>
          <p class="xc-blurb">${esc(c.blurb)}</p>
          <ul class="xc-chips">
            <li><a class="chip chip-lic" href="${esc(upstream)}" target="_blank" rel="noopener" title="${esc(licenceTitle)}">${esc(c.license)}<span class="sr"> — licence, opens the publisher's repository in a new tab</span></a></li>
            <li><span class="chip chip-dl" title="Open VSX downloads">${esc(c.downloadsLabel)}</span></li>
            <li><span class="chip chip-fam">${esc(c.family)}</span></li>
          </ul>
          <div class="xc-actions">
            <button class="btn btn-ghost btn-sm" type="button" data-copy-id="${esc(c.id)}">copy id</button>
            <a class="btn btn-ghost btn-sm" href="${esc(c.registry)}" target="_blank" rel="noopener">registry <span aria-hidden="true">↗</span><span class="sr"> (opens in a new tab)</span></a>
            <span class="btn btn-sm xc-install" role="img" aria-label="Install is not available yet: the catalog index ships with milestone M5" title="Ships with M5 — the checksum-pinned catalog index is not live yet">install · M5</span>
          </div>
        </article>`;
}

function render() {
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const page = readFileSync(PAGE, 'utf8');
  const start = page.indexOf(BEGIN);
  const stop = page.indexOf(END);
  if (start < 0 || stop < 0 || stop < start) {
    console.error(`catalog: ${PAGE} is missing the ${BEGIN} / ${END} markers`);
    process.exit(1);
  }

  const all = data.families.length;
  const stats = `        <p class="cat-stats"><span class="mono">${data.cards.length} extensions</span><span class="mono">${all} families</span><span class="mono">licence gate: ${data.gate.pending} pending</span><span class="mono">generated ${esc(data.generated)}</span></p>\n`;
  const cats = [
    `            <li><button class="cat is-on" type="button" data-family="all" aria-pressed="true">All extensions <span class="cat-n">${data.cards.length}</span></button></li>`,
    ...data.families.map((f) => `            <li><button class="cat" type="button" data-family="${esc(f.key)}" aria-pressed="false">${esc(f.label)} <span class="cat-n">${f.count}</span></button></li>`),
  ].join('\n');
  const grid = data.cards.map(cardHtml).join('\n');

  const block = `${BEGIN}
        <div class="cat-stats">
          <span class="mono">${data.cards.length} extensions</span>
          <span class="mono">${all} families</span>
          <span class="mono">licence gate: ${data.gate.pending} pending</span>
          <span class="mono">generated ${esc(data.generated)}</span>
        </div>
        <div class="catalog">
          <aside class="rail" aria-labelledby="cats-h">
            <p class="rail-h" id="cats-h">// categories</p>
            <ul class="cats" role="list">
${cats}
            </ul>
            <p class="rail-foot">Families group extensions by what they <em>are</em>, not by the language they touch. Every row passed the licence gate in <span class="mono">npm run catalog:scan</span>.</p>
          </aside>
          <div class="catalog-main">
            <div class="toolbar">
              <label class="sr" for="cat-q">Search extensions</label>
              <input class="cat-q" id="cat-q" type="search" placeholder="/ search extensions, publishers, ids…" autocomplete="off" spellcheck="false">
              <label class="sr" for="cat-sort">Sort by</label>
              <select class="cat-sort" id="cat-sort">
                <option value="dl">downloads · high to low</option>
                <option value="name">name · a to z</option>
                <option value="lic">licence</option>
                <option value="pub">publisher</option>
              </select>
              <output class="cat-count" id="cat-count" aria-live="polite" for="cat-q">${data.cards.length} shown</output>
            </div>
            <div class="xgrid" id="xgrid">
${grid}
            </div>
            <p class="cat-empty" id="cat-empty" hidden><b>// no match</b> Nothing in the catalog matches that search and category. Clear the search, or pick another family.</p>
          </div>
        </div>
      ${END}`;
  writeFileSync(PAGE, `${page.slice(0, start)}${block}${page.slice(stop + END.length)}`);
  console.error(`catalog: rendered ${data.cards.length} cards into site/repository.html`);
}

// ---------------------------------------------------------------- check
function check() {
  const fail = (msg) => { console.error(`catalog: ${msg}`); process.exit(1); };
  if (!existsSync(DATA)) fail('site/data/catalog.json missing — run `node tools/catalog.mjs build`');
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const content = JSON.parse(readFileSync(CONTENT, 'utf8'));
  const verified = JSON.parse(readFileSync(VERIFIED, 'utf8'));
  const problems = [];
  const ids = new Set();

  if (!Array.isArray(data.cards) || data.cards.length === 0) fail('catalog has no cards');

  for (const c of data.cards) {
    const at = (m) => problems.push(`${c.id}: ${m}`);
    if (ids.has(c.id)) at('duplicate id');
    ids.add(c.id);
    if (c.id in content.omit) at('listed but omitted from the site');
    if (!(c.family in content.families)) at('unknown family');
    if (!c.name || !c.blurb) at('missing name or blurb');
    if (c.blurb && c.blurb.length > 160) at('blurb too long for a card');
    if (!c.license) at('missing licence');
    if (!Number.isFinite(c.downloads)) at('downloads is not a number');
    if (!/^https:\/\/open-vsx\.org\/extension\/[^/]+\/[^/]+$/.test(c.registry)) at('bad registry url');
    if (c.repository !== null && !/^https?:\/\//.test(c.repository)) at('repository is neither null nor a url');
    if (!c.repository && !c.registry.startsWith('https://open-vsx.org/extension/')) at('no repository and no registry link to credit');
    if (c.id in verified && verified[c.id].spdx === 'NONE') at('id is a recorded refusal');
  }
  for (const [id, why] of Object.entries(content.omit)) {
    if (ids.has(id)) problems.push(`${id}: on the omit list but present (${why.slice(0, 40)}…)`);
  }

  // Every card must appear in the document appendix, which only the gate's
  // accept/verified rows reach — this is what keeps the site and the licence
  // gate from drifting apart while both are offline.
  const doc = readFileSync(DOC, 'utf8');
  for (const c of data.cards) if (!doc.includes(`\`${c.id}\``)) problems.push('id not present in FOSS_EXTENSION_REPOSITORY.md');

  const page = readFileSync(PAGE, 'utf8');
  const start = page.indexOf(BEGIN);
  const stop = page.indexOf(END);
  if (start < 0 || stop < 0 || stop < start) {
    problems.push('repository.html is missing the CATALOG markers');
  } else {
    const block = page.slice(start, stop);
    const shown = [...block.matchAll(/data-id="([^"]+)"/g)].map((m) => m[1]);
    if (shown.length !== data.cards.length) problems.push(`HTML shows ${shown.length} cards, catalog.json has ${data.cards.length} — run \`node tools/catalog.mjs render\``);
    for (const id of shown) if (!ids.has(id)) problems.push(`HTML card ${id} is not in catalog.json`);
    const familiesShown = [...block.matchAll(/<article class="xcard"[^>]*data-family="([^"]+)"/g)].length;
    if (familiesShown !== shown.length) problems.push('a card is missing its data-family attribute');
  }

  if (problems.length) {
    console.error(`catalog: ${problems.length} problem(s) —\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.error(`catalog: OK — ${data.cards.length} cards, ${data.families.length} families, HTML and data in sync, no refused ids, every card credited`);
}

// ---------------------------------------------------------------- cli
const mode = process.argv[2];
if (mode === 'build') build();
else if (mode === 'render') render();
else if (mode === 'check') check();
else {
  console.error('usage: node tools/catalog.mjs build|render|check');
  process.exit(2);
}
